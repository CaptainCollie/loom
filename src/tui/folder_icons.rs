pub(super) fn glyph_for(name: &str) -> char {
    let name = name.to_lowercase();
    ICONS_BY_NAME
        .binary_search_by_key(&name.as_str(), |(key, _)| *key)
        .map(|index| ICONS_BY_NAME[index].1)
        .unwrap_or('\u{f115}')
}
